#!/usr/bin/env python3
"""대사 줄에서 자주 빠지는 강세를 사전대로 채운다. 사용법: stress_fix.py 파일 [파일 ...]"""
import re
import sys

FIX = {
    "Это": "Э́то", "Эту": "Э́ту", "это": "э́то", "было": "бы́ло", "Хуже": "Ху́же", "трогать": "тро́гать",
    "ящик": "я́щик", "открыт": "откры́т", "строчку": "стро́чку", "строчка": "стро́чка", "экономная": "эконо́мная",
    "Скоро": "Ско́ро", "самая": "са́мая", "Письменно": "Пи́сьменно", "раньше": "ра́ньше", "родные": "родны́е",
    "целая": "це́лая", "правда": "пра́вда", "рассказывай": "расска́зывай", "арендатор": "аренда́тор",
    "восемь": "во́семь", "индексация": "индекса́ция", "вправе": "впра́ве", "дальше": "да́льше",
    "Двадцать": "Два́дцать", "угодно": "уго́дно", "пугай": "пуга́й", "задумчивый": "заду́мчивый",
    "тортом": "то́ртом", "стынет": "сты́нет", "сегодня": "сего́дня", "сорок": "со́рок", "тысяч": "ты́сяч",
    "одиннадцати": "оди́ннадцати", "одиннадцать": "оди́ннадцать", "нибудь": "нибу́дь", "Тоже": "То́же",
}
PAT = re.compile(r"(?<![А-Яа-яЁё́])(" + "|".join(sorted(FIX, key=len, reverse=True)) + r")(?![А-Яа-яЁё́])")

for path in sys.argv[1:]:
    head, ko = open(path, encoding="utf-8").read().split("## 한글 해석")
    lines = [PAT.sub(lambda m: FIX[m.group(1)], l) if l.startswith("**") and ":**" in l else l for l in head.split("\n")]
    open(path, "w", encoding="utf-8").write("\n".join(lines) + "## 한글 해석" + ko)
